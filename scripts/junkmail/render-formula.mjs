// junkmail: writes the Homebrew formula for a release.
//
//   node scripts/junkmail/render-formula.mjs <version> <darwin-arm64 sha256> <darwin-x64 sha256> [out-file]
//
// The formula installs the upstream single-executable CLI archive unchanged and wraps it in a
// `junkmail` command that keeps its own data folder and port, so it never collides with an
// official T3 Code install on the same machine.
import { writeFileSync } from "node:fs";

const [version, armSha, intelSha, outFile = "junkmail.rb"] = process.argv.slice(2);
const isSha = (value) => /^[0-9a-f]{64}$/.test(value ?? "");
if (!version || !isSha(armSha) || !isSha(intelSha)) {
  console.error("usage: render-formula.mjs <version> <arm64 sha256> <x64 sha256> [out-file]");
  process.exit(1);
}

const repo = "komcdo/junkmail";
// Intel Macs run the server bundle on this Node (official build, so nothing compiles from source
// on macOS versions Homebrew no longer bottles). Bump both together from nodejs.org/dist SHASUMS256.
const intelNode = {
  version: "24.22.0",
  sha256: "495e3f273c645f3c4677d438304cdfc701729ea5dec5728f5c8e76a2dece4b91",
};
const tag = `junkmail-v${version}`;
const download = (arch) =>
  `https://github.com/${repo}/releases/download/${tag}/t3-${version}-darwin-${arch}.tar.gz`;

const formula = `# Generated by scripts/junkmail/render-formula.mjs in ${repo}; edit that, not this.
class Junkmail < Formula
  desc "AI-triaged work inbox built on T3 Code"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "MIT"

  depends_on :macos

  on_arm do
    url "${download("arm64")}"
    sha256 "${armSha}"
  end
  on_intel do
    url "${download("x64")}"
    sha256 "${intelSha}"
    # Intel archives carry the server bundle instead of a single executable; it runs on Node.
    resource "node" do
      url "https://nodejs.org/dist/v${intelNode.version}/node-v${intelNode.version}-darwin-x64.tar.gz"
      sha256 "${intelNode.sha256}"
    end
  end

  def server_command
    if Hardware::CPU.intel?
      %Q["#{libexec}/node/bin/node" "#{libexec}/bin.mjs"]
    else
      %Q["#{libexec}/t3"]
    end
  end

  def install
    libexec.install Dir["*"]
    resource("node").stage { (libexec/"node").install Dir["*"] } if Hardware::CPU.intel?
    (bin/"junkmail").write <<~SH
      #!/bin/bash
      # Own data folder, so an official T3 Code install on this machine is never touched.
      export T3CODE_HOME="\${JUNKMAIL_HOME:-$HOME/.junkmail}"
      # Web mode otherwise turns the launch folder into a project and opens a thread there; for
      # the service that folder is /, and a disabled default provider aborts startup.
      export T3CODE_AUTO_BOOTSTRAP_PROJECT_FROM_CWD="\${T3CODE_AUTO_BOOTSTRAP_PROJECT_FROM_CWD:-false}"
      # launchd starts services with a bare PATH; agent CLIs usually live in these.
      export PATH="$HOME/.local/bin:#{HOMEBREW_PREFIX}/bin:$PATH"
      if [ "\${1:-}" = "import-t3" ]; then
        shift
        exec /bin/bash "#{libexec}/import-t3.sh" "$@"
      fi
      if [ "\${1:-}" = "open" ]; then
        url="$(#{server_command} pair --ttl 15m 2>&1 | grep -oE 'https?://[^[:space:]]+#token=[A-Za-z0-9]+' | head -1)"
        if [ -z "$url" ]; then
          echo "junkmail is not running. Start it with: brew services start junkmail" >&2
          exit 1
        fi
        echo "$url"
        exec open "$url"
      fi
      exec #{server_command} "$@"
    SH
  end

  service do
    run [opt_bin/"junkmail", "--no-browser", "--port", "3883"]
    keep_alive true
    log_path var/"log/junkmail.log"
    error_log_path var/"log/junkmail.log"
  end

  def caveats
    <<~EOS
      Run it in the background (starts at login, restarts if it stops):
        brew services start junkmail
      Then open it in your browser:
        junkmail open

      Or run it in the foreground for one session:
        junkmail

      Data lives in ~/.junkmail (set JUNKMAIL_HOME to change it).
      Coming from T3 Code? Bring your threads over before the first start:
        junkmail import-t3
      Already started? Bring over just the saved remote connections:
        junkmail import-t3 --connections
      Sign in to the agent CLIs you use (Claude Code, Codex) so threads can run.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/junkmail --version")
  end
end
`;

writeFileSync(outFile, formula);
console.log(`Wrote ${outFile} for ${tag}`);
